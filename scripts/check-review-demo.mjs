import assert from 'node:assert/strict';
import { demoAPI, demoTransition } from '../web/js/review-demo.js';
const values = new Map();
globalThis.localStorage = { getItem: (key) => values.get(key) ?? null, setItem: (key, value) => values.set(key, value) };
const original = JSON.stringify({ text: 'Original text' });
assert.equal((await demoAPI('me')).user.role, 'expert');
const { id } = await demoAPI('tickets', { target: 'knowledge:test', title: 'Demo', snapshot: original, comment: 'Please review' });
await assert.rejects(demoAPI(`tickets/${id}`, { version: 1, action: 'start', comment: 'No permission' }));
await demoAPI('login', { role: 'developer' });
await demoAPI(`tickets/${id}`, { version: 1, action: 'start', comment: 'Started' });
await assert.rejects(demoAPI(`tickets/${id}`, { version: 1, action: 'resubmit', comment: 'Stale' }));
await demoAPI(`tickets/${id}`, { version: 2, action: 'resubmit', comment: 'Updated', demo_text: 'Corrected text' });
let ticket = (await demoAPI('tickets')).tickets[0];
assert.equal(ticket.status, 'recheck');
assert.equal(JSON.parse(ticket.snapshot).text, 'Corrected text');
assert.equal(ticket.events[0].snapshot, original);
await assert.rejects(demoAPI(`tickets/${id}`, { version: 3, action: 'approve', comment: 'Wrong role' }));
await demoAPI('login', { role: 'expert' });
await demoAPI(`tickets/${id}`, { version: 3, action: 'request_changes', comment: 'One more revision' });
await demoAPI('login', { role: 'developer' });
await demoAPI(`tickets/${id}`, { version: 4, action: 'resubmit', comment: 'Ready' });
await demoAPI('login', { role: 'expert' });
ticket = (await demoAPI('tickets')).tickets[0];
assert.throws(() => demoTransition({ ...ticket, current_snapshot: 'changed' }, { role: 'expert' }, { version: 5, action: 'approve' }));
await demoAPI(`tickets/${id}`, { version: 5, action: 'approve', comment: 'Approved demo' });
ticket = (await demoAPI('tickets')).tickets[0];
assert.equal(ticket.status, 'closed');
assert.equal(ticket.events.length, 6);
assert.equal(values.size, 1, 'Demo must use its own storage key');
console.log('OK: static demo roles, revisions, history, persistence and complete review loop');
